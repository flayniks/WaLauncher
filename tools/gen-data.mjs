// Turns the open-source packs in node_modules into the data modules the editor ships with:
//   gl-transitions (MIT)  -> src/data/transitions.js
//   animate.css (MIT)     -> src/data/animations.js
// Run with `npm run gen` after updating either package.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');

// ---------- gl-transitions ----------

// Transitions that need extra image textures, or that only look right with them, are left out.
const SKIP_TRANSITIONS = new Set(['StereoViewer']);

const pretty = (name) =>
  name
    .replace(/[_-]+/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/\bRigth\b/, 'Right')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^./, (c) => c.toUpperCase());

function genTransitions() {
  const pkg = JSON.parse(readFileSync(join(nm, 'gl-transitions/package.json'), 'utf8'));
  const all = JSON.parse(readFileSync(join(nm, 'gl-transitions/gl-transitions.json'), 'utf8'));
  const out = [];
  for (const t of all) {
    if (t.textures && t.textures.length) continue;
    if (SKIP_TRANSITIONS.has(t.name)) continue;
    out.push({
      id: t.name,
      name: pretty(t.name),
      author: t.author,
      license: t.license,
      tags: t.tags || [],
      paramsTypes: t.paramsTypes || {},
      defaultParams: t.defaultParams || {},
      glsl: t.glsl,
    });
  }
  out.sort((a, b) => a.name.localeCompare(b.name));
  const header =
    `// Generated by tools/gen-data.mjs from gl-transitions ${pkg.version} (https://gl-transitions.com).\n` +
    `// Each transition keeps its own author and license (MIT unless noted). Do not edit by hand.\n`;
  writeFileSync(join(root, 'src/data/transitions.js'), header + 'export default ' + JSON.stringify(out, null, 1) + ';\n');
  return out.length;
}

// ---------- animate.css ----------

const CATEGORY = {
  attention_seekers: 'loop',
  back_entrances: 'in',
  back_exits: 'out',
  bouncing_entrances: 'in',
  bouncing_exits: 'out',
  fading_entrances: 'in',
  fading_exits: 'out',
  lightspeed: null, // decided per name
  rotating_entrances: 'in',
  rotating_exits: 'out',
  sliding_entrances: 'in',
  sliding_exits: 'out',
  specials: null,
  zooming_entrances: 'in',
  zooming_exits: 'out',
  flippers: null,
};

function categoryFor(dir, name) {
  if (CATEGORY[dir]) return CATEGORY[dir];
  if (/In(Left|Right|X|Y)?$|In[A-Z]/.test(name) || name === 'jackInTheBox' || name === 'rollIn') return 'in';
  if (/Out/.test(name) || name === 'hinge') return 'out';
  return 'loop';
}

const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '');

// "0.215, 0.61, 0.355, 1" style timing functions are kept as strings; the runtime parses them.
function parseDecls(body) {
  const decls = {};
  for (const part of body.split(';')) {
    const i = part.indexOf(':');
    if (i < 0) continue;
    const k = part.slice(0, i).trim();
    const v = part.slice(i + 1).trim();
    if (k) decls[k] = v;
  }
  return decls;
}

function parseLength(v) {
  v = v.trim();
  if (v === '0') return { e: 0, p: 0 };
  const m = v.match(/^(-?[\d.]+)(%|px)?$/);
  if (!m) throw new Error('length ' + v);
  const n = parseFloat(m[1]);
  if (m[2] === '%') return { e: n / 100, p: 0 };
  return { e: 0, p: n };
}

const deg = (v) => {
  const m = v.trim().match(/^(-?[\d.]+)(deg|turn)?$/);
  if (!m) throw new Error('angle ' + v);
  return m[2] === 'turn' ? parseFloat(m[1]) * 360 : parseFloat(m[1]);
};

// A transform becomes flat components. 3D rotations about X/Y are drawn as a squash (cosine of the angle),
// which is how a flat layer looks when it turns without perspective.
function parseTransform(v) {
  const c = {};
  const re = /([a-zA-Z0-9]+)\(([^)]*)\)/g;
  let m;
  while ((m = re.exec(v))) {
    const fn = m[1];
    const args = m[2].split(',').map((s) => s.trim());
    const addT = (axis, len) => {
      const L = parseLength(len);
      c['t' + axis + 'E'] = (c['t' + axis + 'E'] || 0) + L.e;
      c['t' + axis + 'P'] = (c['t' + axis + 'P'] || 0) + L.p;
    };
    switch (fn) {
      case 'translate3d':
      case 'translate':
        addT('x', args[0]);
        if (args[1] !== undefined) addT('y', args[1]);
        break;
      case 'translateX':
        addT('x', args[0]);
        break;
      case 'translateY':
        addT('y', args[0]);
        break;
      case 'translateZ':
      case 'perspective':
        break;
      case 'scale3d':
        c.sx = parseFloat(args[0]);
        c.sy = parseFloat(args[1]);
        break;
      case 'scale':
        c.sx = parseFloat(args[0]);
        c.sy = parseFloat(args[1] ?? args[0]);
        break;
      case 'scaleX':
        c.sx = parseFloat(args[0]);
        break;
      case 'scaleY':
        c.sy = parseFloat(args[0]);
        break;
      case 'rotate':
      case 'rotateZ':
        c.rot = (c.rot || 0) + deg(args[0]);
        break;
      case 'rotate3d': {
        const [x, y, z] = args.slice(0, 3).map(Number);
        const a = deg(args[3]);
        if (z) c.rot = (c.rot || 0) + a * Math.sign(z);
        else if (x) c.rx = (c.rx || 0) + a;
        else if (y) c.ry = (c.ry || 0) + a;
        break;
      }
      case 'rotateX':
        c.rx = (c.rx || 0) + deg(args[0]);
        break;
      case 'rotateY':
        c.ry = (c.ry || 0) + deg(args[0]);
        break;
      case 'skewX':
        c.skx = deg(args[0]);
        break;
      case 'skewY':
        c.sky = deg(args[0]);
        break;
      case 'skew':
        c.skx = deg(args[0]);
        c.sky = deg(args[1] ?? '0');
        break;
      default:
        throw new Error('transform fn ' + fn);
    }
  }
  return c;
}

function parseOrigin(v) {
  if (!v) return null;
  const words = v.trim().split(/\s+/);
  let x = 0;
  let y = 0;
  for (const w of words) {
    if (w === 'left') x = -0.5;
    else if (w === 'right') x = 0.5;
    else if (w === 'top') y = -0.5;
    else if (w === 'bottom') y = 0.5;
  }
  return [x, y];
}

function parseAnimation(file, dir) {
  const css = stripComments(readFileSync(file, 'utf8'));
  const kfMatch = css.match(/@keyframes\s+([\w-]+)\s*\{([\s\S]*)\}\s*\.[.\w-]+\s*\{([\s\S]*?)\}/);
  if (!kfMatch) throw new Error('no keyframes in ' + file);
  const name = kfMatch[1];
  const kfBody = kfMatch[2];
  const cls = parseDecls(kfMatch[3]);

  const frames = []; // {offset, decls}
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(kfBody))) {
    const decls = parseDecls(m[2]);
    for (let sel of m[1].split(',')) {
      sel = sel.trim();
      const offset = sel === 'from' ? 0 : sel === 'to' ? 1 : parseFloat(sel) / 100;
      frames.push({ offset, decls });
    }
  }
  // Merge frames that share an offset (animate.css lists timing functions separately from values).
  const byOffset = new Map();
  for (const f of frames) {
    const prev = byOffset.get(f.offset) || {};
    byOffset.set(f.offset, { ...prev, ...f.decls });
  }
  const offsets = [...byOffset.keys()].sort((a, b) => a - b);

  let origin = parseOrigin(cls['transform-origin']);
  const tracks = { opacity: [], transform: [] };
  for (const o of offsets) {
    const d = byOffset.get(o);
    const ease = d['animation-timing-function'] || null;
    if (d['transform-origin'] && !origin) origin = parseOrigin(d['transform-origin']);
    if (d.opacity !== undefined) tracks.opacity.push([o, parseFloat(d.opacity), ease]);
    if (d.transform !== undefined) tracks.transform.push([o, d.transform === 'none' ? {} : parseTransform(d.transform), ease]);
  }
  if (!tracks.opacity.length) delete tracks.opacity;
  if (!tracks.transform.length) delete tracks.transform;

  let duration = 1;
  const dur = cls['animation-duration'];
  if (dur) {
    const mm = dur.match(/\*\s*([\d.]+)/);
    if (mm) duration = parseFloat(mm[1]);
    else if (/^[\d.]+s$/.test(dur)) duration = parseFloat(dur);
  }
  return {
    id: name,
    name: pretty(name),
    category: categoryFor(dir, name),
    group: pretty(dir),
    duration,
    ease: cls['animation-timing-function'] || 'ease',
    origin: origin || [0, 0],
    tracks,
  };
}

function genAnimations() {
  const pkg = JSON.parse(readFileSync(join(nm, 'animate.css/package.json'), 'utf8'));
  const srcDir = join(nm, 'animate.css/source');
  const out = [];
  for (const dir of readdirSync(srcDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    for (const f of readdirSync(join(srcDir, dir.name))) {
      if (!f.endsWith('.css')) continue;
      out.push(parseAnimation(join(srcDir, dir.name, f), dir.name));
    }
  }
  out.sort((a, b) => a.category.localeCompare(b.category) || a.group.localeCompare(b.group) || a.name.localeCompare(b.name));
  const header =
    `// Generated by tools/gen-data.mjs from animate.css ${pkg.version} (https://animate.style, MIT, Daniel Eden & contributors).\n` +
    `// Keyframes are parsed from the CSS sources into flat transform tracks. Do not edit by hand.\n`;
  writeFileSync(join(root, 'src/data/animations.js'), header + 'export default ' + JSON.stringify(out) + ';\n');
  return out.length;
}

